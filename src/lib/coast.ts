const pos = (d: District) => d.coastKm ?? 0
/** Аэропорт Газипаша-Аланья (~38 км на восток от центра). */
export const gzpKm = (d: District) => Math.max(4, Math.round(Math.abs(38 - pos(d)))) + (d.inland ? 2 : 0)
/** Аэропорт Анталии (~125 км на запад от центра). */
export const aytKm = (d: District) => Math.round(125 + pos(d) + (d.inland ? 3 : 0))
